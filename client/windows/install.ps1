# Makia Windows Full Device Connector — one installer, bundled OpenVPN runtime.
# The user installs Makia once. The signed OpenVPN dependency supplies its
# required Windows network driver; OpenVPN/Outline do not exist in Windows RAS.
param([string]$SourceDir = $PSScriptRoot,[switch]$SkipOpenVpnSetup)

$ErrorActionPreference = "Stop"
$target = Join-Path $env:LOCALAPPDATA "Makia\Connector\bin"
$openVpnMsiName = "OpenVPN-2.6.23-I002-amd64.msi"
$openVpnMsi = Join-Path $SourceDir $openVpnMsiName
$openVpnShaFile = Join-Path $SourceDir "$openVpnMsiName.sha256"

function Get-OpenVpnExe {
  foreach ($path in @(
    "$env:ProgramFiles\OpenVPN\bin\openvpn.exe",
    "${env:ProgramFiles(x86)}\OpenVPN\bin\openvpn.exe"
  )) {
    if ($path -and (Test-Path -LiteralPath $path)) { return $path }
  }
  return $null
}

# Packaging integrity check, including on hosts with an existing OpenVPN
# installation. SHA is generated by the verified official-source CI build.
if (!(Test-Path -LiteralPath $openVpnMsi) -or !(Test-Path -LiteralPath $openVpnShaFile)) {
  throw "Makia package is incomplete: the verified OpenVPN driver/runtime installer is missing."
}
$expected = ((Get-Content -LiteralPath $openVpnShaFile -Raw).Trim()).ToLowerInvariant()
if ($expected -notmatch '^[a-f0-9]{64}$') { throw "Invalid OpenVPN package SHA256 manifest" }
$actual = (Get-FileHash -LiteralPath $openVpnMsi -Algorithm SHA256).Hash.ToLowerInvariant()
if ($actual -ne $expected) { throw "OpenVPN package checksum mismatch; installation cancelled" }
$signature = Get-AuthenticodeSignature -LiteralPath $openVpnMsi
if ($signature.Status -ne 'Valid' -or
    !$signature.SignerCertificate -or
    $signature.SignerCertificate.Subject -notmatch 'OpenVPN') {
  throw "OpenVPN publisher signature is not valid; installation cancelled"
}

$existingOpenVpn = Get-OpenVpnExe
if (!$existingOpenVpn -and !$SkipOpenVpnSetup) {
  # Only the vendor driver/runtime install needs UAC; Makia's URI handler stays
  # in the requesting user's HKCU profile, even with separate admin accounts.
  Write-Host "Installing the bundled signed OpenVPN runtime and network driver (one-time UAC)..." -ForegroundColor Cyan
  $arguments = "/i `"$openVpnMsi`" /qn /norestart"
  $process = Start-Process -FilePath "msiexec.exe" -ArgumentList $arguments -Verb RunAs -Wait -PassThru
  if ($process.ExitCode -notin @(0,3010)) {
    throw "The bundled OpenVPN runtime installation failed (MSI code $($process.ExitCode))"
  }
  $existingOpenVpn = Get-OpenVpnExe
  if (!$existingOpenVpn) { throw "OpenVPN executable missing after successful installer; setup incomplete" }
}
if (!$existingOpenVpn -and !$SkipOpenVpnSetup) {
  throw "OpenVPN runtime/driver is unavailable"
}

New-Item -ItemType Directory -Force -Path $target | Out-Null
foreach ($name in @("MakiaClientConnector.exe","sing-box.exe","wstunnel.exe","wintun.dll","WINTUN-LICENSE.txt")) {
  $src = Join-Path $SourceDir $name
  if (!(Test-Path -LiteralPath $src)) { throw "Missing $name in Makia package" }
  Copy-Item -LiteralPath $src -Destination (Join-Path $target $name) -Force
}
$connector = Join-Path $target "MakiaClientConnector.exe"
$runtime = Join-Path $target "sing-box.exe"
$wstunnel = Join-Path $target "wstunnel.exe"
$wintun = Join-Path $target "wintun.dll"

$base = "HKCU:\Software\Classes\makia"
New-Item -Force -Path $base | Out-Null
Set-Item -Path $base -Value "URL:Makia Client Connector"
New-ItemProperty -Path $base -Name "URL Protocol" -Value "" -PropertyType String -Force | Out-Null
New-Item -Force -Path "$base\DefaultIcon" | Out-Null
Set-Item -Path "$base\DefaultIcon" -Value ('"' + $connector + '",0')
New-Item -Force -Path "$base\shell\open\command" | Out-Null
Set-Item -Path "$base\shell\open\command" -Value ('"' + $connector + '" "%1"')

foreach ($path in @($connector,$runtime,$wstunnel,$wintun)) {
  if (!(Test-Path -LiteralPath $path)) { throw "Makia Windows installation missing: $path" }
}
$registered = (Get-Item "$base\shell\open\command").GetValue("")
if ([string]::IsNullOrWhiteSpace($registered) -or !$registered.Contains("MakiaClientConnector.exe")) {
  throw "makia:// registration failed"
}
$state = @{
  version = "1.6.5.1"
  mode = "full-device"
  connector = $connector
  runtime = $runtime
  wstunnel = $wstunnel
  wintun = $wintun
  openvpn = if ($existingOpenVpn) { $existingOpenVpn } else { "skipped-in-ci" }
  installed_at = (Get-Date).ToUniversalTime().ToString("o")
} | ConvertTo-Json -Depth 3
[System.IO.File]::WriteAllText((Join-Path $target "install-state.json"),$state,(New-Object System.Text.UTF8Encoding($false)))
Write-Host "Makia Windows Connector 1.6.5.1 installed. Open the Makia Client Portal and click Direct Connect." -ForegroundColor Green
Write-Host "Connector: $connector"
Write-Host "Outline is handled by Makia's bundled sing-box runtime. Browser-only users need only the Makia extension."
